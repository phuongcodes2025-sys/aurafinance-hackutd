import { useEffect, useState } from 'react'
import type { FormEvent } from 'react'
import { message, request } from './api'
import type { Analysis, ChatResponse, EconomicEvent, Health, Impact, IncomeRange, Profile, ProfileInput } from './api'

const INITIAL_PROFILE: ProfileInput = {
  name: 'Demo user', occupation: '', incomeRange: '60k-100k',
  businessOwner: false, investor: false, propertyOwner: false,
}
const DALLAS_PROFILE: ProfileInput = {
  name: 'Dallas demo', occupation: 'Dallas small business owner', incomeRange: '60k-100k',
  businessOwner: true, investor: true, propertyOwner: true,
}
const AREAS = { income: 'Income', business: 'Business', investments: 'Investments', realEstate: 'Real estate' }
const RISKS = { low: 'Low attention', moderate: 'Moderate attention', high: 'High attention', notApplicable: 'Not applicable' }
const INCOME_LABELS: Record<IncomeRange, string> = {
  'under-30k': 'Under $30,000',
  '30k-60k': '$30,000 - $60,000',
  '60k-100k': '$60,000 - $100,000',
  'over-100k': 'Over $100,000',
}

function ImpactCard({ impact }: { impact: Impact }) {
  return (
    <article className={`impact-card risk-${impact.risk}`}>
      <div className="card-top">
        <h3>{AREAS[impact.area]}</h3>
        <span className={`risk-badge ${impact.risk}`}>{RISKS[impact.risk]}</span>
      </div>
      <h4>{impact.summary}</h4>
      <p>{impact.explanation}</p>
      {impact.considerations.length > 0 && (
        <div className="considerations">
          <span className="eyebrow">Things to consider</span>
          <ul>{impact.considerations.map(item => <li key={item}>{item}</li>)}</ul>
        </div>
      )}
      {impact.ruleId && <small className="rule-label">Rule: {impact.ruleId}</small>}
    </article>
  )
}

function ChatBox({ analysis, enabled, onBusy }: {
  analysis: Analysis
  enabled: boolean
  onBusy: (busy: boolean) => void
}) {
  const [question, setQuestion] = useState('')
  const [reply, setReply] = useState<{ question: string; answer: string } | null>(null)
  const [error, setError] = useState('')
  const [busy, setBusy] = useState(false)

  async function ask(event: FormEvent<HTMLFormElement>) {
    event.preventDefault()
    if (!question.trim() || busy || !enabled) return
    setBusy(true)
    onBusy(true)
    setError('')
    setReply(null)
    const submitted = question.trim()
    try {
      const result = await request<ChatResponse>('/chat', { analysisId: analysis.id, question: submitted })
      setReply({ question: submitted, answer: result.answer })
      setQuestion('')
    } catch (error) {
      setError(message(error))
    } finally {
      setBusy(false)
      onBusy(false)
    }
  }

  return (
    <section className="panel chat-panel" aria-labelledby="chat-title">
      <div className="section-heading">
        <div><span className="eyebrow">04 / Understand the why</span><h2 id="chat-title">Ask your copilot</h2></div>
        <span className="tag">{enabled ? 'AI explanations' : 'AI not configured'}</span>
      </div>
      <p>Ask about <strong>{analysis.event.title.toLowerCase()}</strong> and the profile used above. AI explains the rules; it does not calculate your score.</p>
      {!enabled && (
        <div className="notice">AI is unavailable until the backend has an API key. The impact cards and considerations above are generated by business rules, not AI.</div>
      )}
      <form onSubmit={ask}>
        <label htmlFor="question">Your question</label>
        <textarea
          id="question" value={question} onChange={event => setQuestion(event.target.value)}
          placeholder="Why should a business owner pay attention to higher rates?"
          maxLength={1000} disabled={!enabled || busy} required rows={3}
        />
        <div className="chat-actions">
          <small>Do not include private financial details.</small>
          <button className="button primary" disabled={!enabled || busy || !question.trim()}>
            {busy ? 'Explaining...' : 'Ask AI'}
          </button>
        </div>
      </form>
      {error && <p className="error" role="alert">{error}</p>}
      {reply && (
        <div className="ai-reply" role="status">
          <span className="eyebrow">AI-generated explanation</span>
          <h3>{reply.question}</h3>
          <p className="whitespace-pre-wrap">{reply.answer}</p>
          <small>Verify AI outputs. Educational information, not financial advice.</small>
        </div>
      )}
    </section>
  )
}

export default function App() {
  const [events, setEvents] = useState<EconomicEvent[]>([])
  const [aiConfigured, setAiConfigured] = useState(false)
  const [profile, setProfile] = useState<ProfileInput>(INITIAL_PROFILE)
  const [eventId, setEventId] = useState<number | null>(null)
  const [analysis, setAnalysis] = useState<Analysis | null>(null)
  const [loading, setLoading] = useState(true)
  const [loadError, setLoadError] = useState('')
  const [error, setError] = useState('')
  const [analyzing, setAnalyzing] = useState(false)
  const [chatBusy, setChatBusy] = useState(false)
  const [reload, setReload] = useState(0)
  const busy = analyzing || chatBusy

  useEffect(() => {
    const controller = new AbortController()
    setLoading(true)
    setLoadError('')
    async function load() {
      try {
        const [availableEvents, health] = await Promise.all([
          request<EconomicEvent[]>('/events', undefined, controller.signal),
          request<Health>('/health', undefined, controller.signal),
        ])
        if (!availableEvents.length) throw new Error('No demo events are available. Check the backend database.')
        if (controller.signal.aborted) return
        setEvents(availableEvents)
        setAiConfigured(health.aiConfigured)
        setEventId(availableEvents[0].id)
      } catch (error) {
        if (!controller.signal.aborted) setLoadError(message(error))
      } finally {
        if (!controller.signal.aborted) setLoading(false)
      }
    }
    void load()
    return () => controller.abort()
  }, [reload])

  function changeProfile(next: ProfileInput) {
    setProfile(next)
    setAnalysis(null)
    setError('')
  }

  async function runAnalysis(event: FormEvent<HTMLFormElement>) {
    event.preventDefault()
    if (eventId === null || busy || !profile.occupation.trim()) return
    setAnalyzing(true)
    setAnalysis(null)
    setError('')
    try {
      const saved = await request<Profile>('/profile', profile)
      const result = await request<Analysis>('/analyze', { userId: saved.id, eventId })
      setAnalysis(result)
    } catch (error) {
      setError(message(error))
    } finally {
      setAnalyzing(false)
    }
  }

  return (
    <div className="app-shell">
      <header className="topbar">
        <a className="brand" href="#top"><span className="brand-mark" aria-hidden="true">a</span>Aura<span>Finance</span></a>
        <div className="header-tags"><span className="tag">HackUTD MVP</span><span className="demo-dot">Synthetic data only</span></div>
      </header>
      <main id="top">
        <section className="hero">
          <div className="hero-copy">
            <span className="eyebrow">Finance Impact Copilot</span>
            <h1>Big economic shifts.<br /><span>Your personal perspective.</span></h1>
            <p>Connect the headlines to your income, business, investments, and real estate. Explore a scenario. Understand the possible impact.</p>
          </div>
          <div className="hero-aside">
            <span className="eyebrow">A clearer picture in three steps</span>
            <ol><li>Build your demo profile</li><li>Choose an economic event</li><li>Explore the impact and ask why</li></ol>
            <span className="tag">Rules first. AI explains.</span>
          </div>
        </section>

        <div className="demo-banner"><strong>Learning, not forecasting.</strong> These are hypothetical scenarios and qualitative attention labels, not live news or financial advice.</div>

        {loading ? <div className="panel" role="status">Loading demo scenarios...</div> : loadError ? (
          <div className="panel"><p className="error" role="alert">{loadError}</p><button className="button secondary" onClick={() => setReload(value => value + 1)}>Retry connection</button></div>
        ) : (
          <>
            <form onSubmit={runAnalysis} className="setup-grid">
              <section className="panel" aria-labelledby="profile-title">
                <div className="section-heading">
                  <div><span className="eyebrow">01 / Your context</span><h2 id="profile-title">Demo financial profile</h2></div>
                </div>
                <p>No account needed. Use a fictional profile to explore your exposure.</p>
                <button type="button" className="button secondary demo-button" disabled={busy} onClick={() => {
                  changeProfile(DALLAS_PROFILE)
                  setEventId(events.find(event => event.id === 2)?.id ?? events[0].id)
                }}>Use Dallas business owner demo</button>
                <fieldset disabled={busy}>
                  <label htmlFor="occupation">Occupation</label>
                  <input id="occupation" value={profile.occupation} required maxLength={100} placeholder="e.g. Student or small business owner"
                    onChange={event => changeProfile({ ...profile, occupation: event.target.value })} />
                  <label htmlFor="income">Annual income range (USD)</label>
                  <select id="income" value={profile.incomeRange}
                    onChange={event => changeProfile({ ...profile, incomeRange: event.target.value as IncomeRange })}>
                    <option value="under-30k">Under $30,000</option>
                    <option value="30k-60k">$30,000 - $60,000</option>
                    <option value="60k-100k">$60,000 - $100,000</option>
                    <option value="over-100k">Over $100,000</option>
                  </select>
                  <span className="field-label">Which areas apply to this demo profile?</span>
                  <div className="exposure-options">
                    {([
                      ['businessOwner', 'Business owner'],
                      ['investor', 'Investor'],
                      ['propertyOwner', 'Property owner'],
                    ] as const).map(([key, label]) => (
                      <label className="checkbox-label" key={key}>
                        <input type="checkbox" checked={profile[key]} onChange={event => changeProfile({ ...profile, [key]: event.target.checked })} />
                        {label}
                      </label>
                    ))}
                  </div>
                </fieldset>
                <small>Income and occupation add context, not calculated dollar impacts.</small>
              </section>

              <section className="panel events-panel" aria-labelledby="event-title">
                <span className="eyebrow">02 / The bigger picture</span><h2 id="event-title">Choose an economic event</h2>
                <p>Four curated scenarios. No real-time data or market predictions.</p>
                <fieldset disabled={busy} className="event-options">
                  <legend className="sr-only">Economic event</legend>
                  {events.map(event => (
                    <label className={`event-option ${eventId === event.id ? 'selected' : ''}`} key={event.id}>
                      <input type="radio" name="event" value={event.id} checked={eventId === event.id} onChange={() => {
                        setEventId(event.id)
                        setAnalysis(null)
                        setError('')
                      }} />
                      <span><strong>{event.title}</strong><small>{event.description}</small></span>
                    </label>
                  ))}
                </fieldset>
                <button className="button primary analyze-button" disabled={busy || !profile.occupation.trim() || eventId === null}>
                  {analyzing ? 'Analyzing your scenario...' : 'Analyze impact'}
                  <span aria-hidden="true">{analyzing ? '...' : '\u2192'}</span>
                </button>
                {error && <p className="error" role="alert">{error}</p>}
              </section>
            </form>

            {analysis ? (
              <div aria-live="polite">
                <section className="results" aria-labelledby="results-title">
                  <div className="section-heading result-heading">
                    <div><span className="eyebrow">03 / Your impact dashboard</span><h2 id="results-title">{analysis.event.title}</h2><p>For {analysis.profile.occupation} / {INCOME_LABELS[analysis.profile.incomeRange]}</p></div>
                    <span className="tag">Deterministic business rules</span>
                  </div>
                  <div className="impact-grid">{analysis.impacts.map(impact => <ImpactCard key={impact.area} impact={impact} />)}</div>
                  <details className="assumptions"><summary>How to interpret this analysis</summary><ul>{analysis.assumptions.map(item => <li key={item}>{item}</li>)}</ul></details>
                </section>
                <ChatBox key={analysis.id} analysis={analysis} enabled={aiConfigured} onBusy={setChatBusy} />
              </div>
            ) : (
              <section className="empty-state" aria-live="polite">
                <span className="eyebrow">{analyzing ? 'Connecting context to the economy' : 'Your impact dashboard starts here'}</span>
                <h2>{analyzing ? 'Applying the business rules...' : 'A little context. A clearer picture.'}</h2>
                <p>Complete the profile and select an event to see four impact cards.</p>
                <div className="empty-areas">{Object.values(AREAS).map(area => <span key={area}>{area}</span>)}</div>
              </section>
            )}
          </>
        )}
      </main>
      <footer><strong>Aura Finance</strong><span>Built for HackUTD. Educational prototype, not financial advice.</span><span>{aiConfigured ? 'AI provider configured' : 'Rule-based demo / AI not configured'}</span></footer>
    </div>
  )
}
